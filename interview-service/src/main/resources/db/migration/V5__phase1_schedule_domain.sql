-- One live item per application and round, so a batch cannot double-book the same candidate for
-- the same stage of the pipeline.
CREATE UNIQUE INDEX IF NOT EXISTS ux_schedule_item_active_application_round
    ON schedule_item(application_id, interview_round)
    WHERE status NOT IN ('CANCELLED', 'SUPERSEDED', 'CANDIDATE_DECLINED');

-- Exactly one primary hiring manager per item.
CREATE UNIQUE INDEX IF NOT EXISTS ux_schedule_item_single_primary_hm
    ON schedule_item_participant(item_id)
    WHERE participant_role = 'PRIMARY_HM';

CREATE UNIQUE INDEX IF NOT EXISTS ux_schedule_item_participant_unique
    ON schedule_item_participant(item_id, user_id);

CREATE UNIQUE INDEX IF NOT EXISTS ux_schedule_item_legacy_interview
    ON schedule_item(legacy_interview_id)
    WHERE legacy_interview_id IS NOT NULL;

-- A group must contain at least one item. This cannot be a plain CHECK, because the group row is
-- necessarily inserted before its items. A deferred constraint trigger asks the question at commit
-- time instead, which is the only moment the answer is meaningful.
CREATE OR REPLACE FUNCTION schedule_group_has_items() RETURNS trigger AS $trigger$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM schedule_item WHERE group_id = NEW.id) THEN
        RAISE EXCEPTION 'Schedule group % has no items', NEW.id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END;
$trigger$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_schedule_group_has_items ON schedule_group;
CREATE CONSTRAINT TRIGGER trg_schedule_group_has_items
    AFTER INSERT ON schedule_group
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION schedule_group_has_items();

