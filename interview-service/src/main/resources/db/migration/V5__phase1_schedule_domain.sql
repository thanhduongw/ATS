);

CREATE TABLE IF NOT EXISTS schedule_item_confirmation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES schedule_item(id) ON DELETE CASCADE,
    revision INTEGER NOT NULL,
    party VARCHAR(32) NOT NULL,
    decision VARCHAR(32) NOT NULL,
    actor_user_id BIGINT NOT NULL,
    reason VARCHAR(500),
    decided_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_schedule_confirmation_party CHECK (party IN ('HIRING_MANAGER', 'CANDIDATE')),
    CONSTRAINT ck_schedule_confirmation_decision
        CHECK (decision IN ('CONFIRMED', 'CHANGE_REQUESTED', 'DECLINED'))
);

CREATE TABLE IF NOT EXISTS schedule_item_revision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL,
    revision INTEGER NOT NULL,
    start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at TIMESTAMP WITH TIME ZONE NOT NULL,
    zone_id VARCHAR(64) NOT NULL,
    format VARCHAR(16) NOT NULL,
    meeting_link VARCHAR(1000),
    work_location_id BIGINT,
    meeting_room_id BIGINT,
    primary_hm_id BIGINT NOT NULL,
    status_at_snapshot VARCHAR(40) NOT NULL,
    created_by_user_id BIGINT NOT NULL,
    reason VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    superseded_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ux_schedule_item_revision UNIQUE (item_id, revision)
