CREATE TABLE IF NOT EXISTS schedule_transition_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type VARCHAR(24) NOT NULL,
    aggregate_id BIGINT NOT NULL,
    aggregate_version BIGINT,
    item_revision INTEGER,
    from_status VARCHAR(40) NOT NULL,
    to_status VARCHAR(40) NOT NULL,
    action VARCHAR(40) NOT NULL,
    actor_user_id BIGINT,
    actor_role VARCHAR(32),
    reason VARCHAR(500),
    admin_override BOOLEAN NOT NULL DEFAULT FALSE,
    correlation_id VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_schedule_transition_aggregate CHECK (aggregate_type IN ('ITEM', 'GROUP')),
    -- An override is a deviation from policy, so it may never be recorded without a reason.
    CONSTRAINT ck_schedule_transition_override_reason
        CHECK (admin_override = FALSE OR reason IS NOT NULL)
);

-- ---------------------------------------------------------------------------------------------
-- 2. Resource reservation ledger
-- ---------------------------------------------------------------------------------------------

-- Required for an exclusion constraint that mixes equality on scalars with range overlap.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS resource_reservation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_type VARCHAR(32) NOT NULL,
    resource_id BIGINT NOT NULL,
    start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(24) NOT NULL,
    schedule_item_id BIGINT NOT NULL,
    schedule_item_revision INTEGER NOT NULL,
    schedule_group_id BIGINT,
    released_at TIMESTAMP WITH TIME ZONE,
    release_reason VARCHAR(255),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_resource_reservation_type
        CHECK (resource_type IN ('HIRING_MANAGER', 'CANDIDATE', 'MEETING_ROOM')),
    CONSTRAINT ck_resource_reservation_status
        CHECK (status IN ('HELD', 'CONFIRMED', 'RELEASED')),
    CONSTRAINT ck_resource_reservation_range CHECK (end_at > start_at),
    CONSTRAINT ck_resource_reservation_released
        CHECK (status <> 'RELEASED' OR released_at IS NOT NULL)
);

-- The invariant that actually decides a race: no resource can be held twice for overlapping time.
-- Released rows drop out of the constraint but stay for audit.
ALTER TABLE resource_reservation
    DROP CONSTRAINT IF EXISTS ux_resource_reservation_no_overlap;
ALTER TABLE resource_reservation
    ADD CONSTRAINT ux_resource_reservation_no_overlap
    EXCLUDE USING gist (
        resource_type WITH =,
        resource_id WITH =,
        tstzrange(start_at, end_at, '[)') WITH &&
    ) WHERE (status <> 'RELEASED');

