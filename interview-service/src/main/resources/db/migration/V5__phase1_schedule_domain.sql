-- Phase 1 expand migration: canonical schedule aggregate, state-transition log and resource
-- reservation ledger. Additive only. The legacy `interview` table is left in place and keeps
-- serving reads until the Phase 7 contract migration removes it.

-- ---------------------------------------------------------------------------------------------
-- 1. Aggregate
-- ---------------------------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS schedule_group (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    department_id BIGINT,
    job_posting_id BIGINT,
    job_requisition_id BIGINT,
    interview_round INTEGER NOT NULL,
    allocation_mode VARCHAR(32) NOT NULL,
    break_minutes INTEGER NOT NULL DEFAULT 0,
    zone_id VARCHAR(64) NOT NULL,
    status VARCHAR(40) NOT NULL,
    created_by_user_id BIGINT NOT NULL,
    cancelled_at TIMESTAMP WITH TIME ZONE,
    cancel_reason VARCHAR(500),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_schedule_group_allocation_mode
        CHECK (allocation_mode IN ('SAME_START', 'SEQUENTIAL')),
    CONSTRAINT ck_schedule_group_break_minutes CHECK (break_minutes >= 0),
    CONSTRAINT ck_schedule_group_round CHECK (interview_round >= 1),
    CONSTRAINT ck_schedule_group_status CHECK (status IN (
        'DRAFT', 'PENDING_HM', 'PARTIALLY_APPROVED', 'HM_CHANGE_REQUESTED', 'PENDING_CANDIDATE',
        'PARTIALLY_CONFIRMED', 'CONFIRMED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE IF NOT EXISTS schedule_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES schedule_group(id),
    application_id BIGINT NOT NULL,
    job_posting_id BIGINT NOT NULL,
    job_requisition_id BIGINT,
    interview_round INTEGER NOT NULL,
    scorecard_template_id BIGINT,
    candidate_id BIGINT NOT NULL,
    candidate_user_id_snapshot BIGINT,
    candidate_name_snapshot VARCHAR(255) NOT NULL,
    department_id BIGINT,
    assigned_recruiter_id BIGINT,
    start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_minutes INTEGER NOT NULL,
    zone_id VARCHAR(64) NOT NULL,
    format VARCHAR(16) NOT NULL,
    meeting_link VARCHAR(1000),
    meeting_link_source VARCHAR(32),
    external_calendar_event_id VARCHAR(255),
    work_location_id BIGINT,
    meeting_room_id BIGINT,
    internal_note TEXT,
    candidate_visible_note TEXT,
    status VARCHAR(40) NOT NULL,
    primary_hm_id BIGINT NOT NULL,
    revision INTEGER NOT NULL DEFAULT 1,
    superseded_by_item_id BIGINT,
    supersedes_item_id BIGINT,
    hm_confirmed_at TIMESTAMP WITH TIME ZONE,
    candidate_confirmed_at TIMESTAMP WITH TIME ZONE,
    actual_start_at TIMESTAMP WITH TIME ZONE,
    actual_end_at TIMESTAMP WITH TIME ZONE,
    cancelled_at TIMESTAMP WITH TIME ZONE,
    cancel_reason VARCHAR(500),
    legacy_interview_id BIGINT,
    legacy_review_required BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_schedule_item_format CHECK (format IN ('ONLINE', 'OFFLINE')),
    CONSTRAINT ck_schedule_item_link_source
        CHECK (meeting_link_source IS NULL OR meeting_link_source IN ('MANUAL', 'GOOGLE_CALENDAR')),
    CONSTRAINT ck_schedule_item_duration CHECK (duration_minutes > 0),
    CONSTRAINT ck_schedule_item_range CHECK (end_at > start_at),
    CONSTRAINT ck_schedule_item_revision CHECK (revision >= 1),
    CONSTRAINT ck_schedule_item_round CHECK (interview_round >= 1),
    CONSTRAINT ck_schedule_item_status CHECK (status IN (
        'DRAFT', 'PENDING_HM', 'HM_CHANGE_REQUESTED', 'PENDING_CANDIDATE',
        'CANDIDATE_CHANGE_REQUESTED', 'CANDIDATE_DECLINED', 'CONFIRMED', 'IN_PROGRESS',
        'COMPLETED_PENDING_EVALUATION', 'EVALUATED', 'CANDIDATE_NO_SHOW', 'INTERVIEWER_NO_SHOW',
        'CANCELLED', 'SUPERSEDED')),
    -- An online interview must carry the link the candidate is told to join, and an offline one a
    -- place to go. Enforced here so no caller can publish an item nobody can attend. Rows carried
    -- over from the legacy table are exempt: incomplete history is a fact to report, not something
    -- to fabricate a venue for.
    CONSTRAINT ck_schedule_item_venue CHECK (
        legacy_interview_id IS NOT NULL
        OR status IN ('DRAFT', 'CANCELLED', 'SUPERSEDED')
        OR (format = 'ONLINE' AND meeting_link IS NOT NULL)
        OR (format = 'OFFLINE' AND (work_location_id IS NOT NULL OR meeting_room_id IS NOT NULL)))
);

CREATE TABLE IF NOT EXISTS schedule_item_participant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES schedule_item(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL,
