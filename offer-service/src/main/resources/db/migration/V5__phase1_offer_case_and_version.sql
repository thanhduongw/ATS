-- Phase 1 expand migration: offer case, version chain, sealed-version immutability and the
-- transition log. Additive only; no existing offer row changes status here.

-- ---------------------------------------------------------------------------------------------
-- 1. Case aggregate and version chain
-- ---------------------------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS offer_case (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL,
    department_id BIGINT,
    assigned_recruiter_id BIGINT,
    candidate_id BIGINT,
    candidate_name_snapshot VARCHAR(255),
    job_requisition_id BIGINT,
    selection_decision_id BIGINT,
    status VARCHAR(32) NOT NULL,
    current_offer_id BIGINT,
    version_counter INTEGER NOT NULL DEFAULT 0,
    closed_at TIMESTAMP WITH TIME ZONE,
    legacy_review_required BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_offer_case_status CHECK (status IN (
        'OPEN', 'CLOSED_ACCEPTED', 'CLOSED_DECLINED', 'CLOSED_EXPIRED', 'CLOSED_WITHDRAWN',
        'CLOSED_CANCELLED')),
    CONSTRAINT ck_offer_case_version_counter CHECK (version_counter >= 0),
    CONSTRAINT ck_offer_case_closed CHECK (status = 'OPEN' OR closed_at IS NOT NULL)
);

-- An application may only have one open negotiation at a time.
--
-- Rows flagged legacy_review_required are excluded. Some historical applications carry two live
-- offers, which the new model has no honest representation for. Closing one of them would invent a
-- decision nobody made, so those rows are quarantined behind the flag and listed in
-- offer_migration_report. The invariant is fully enforced for everything written from here on, and
-- the flag is cleared as HR resolves each case.
CREATE UNIQUE INDEX IF NOT EXISTS ux_offer_case_open_application
    ON offer_case(application_id)
    WHERE status = 'OPEN' AND legacy_review_required = FALSE;

CREATE INDEX IF NOT EXISTS ix_offer_case_application ON offer_case(application_id);
CREATE INDEX IF NOT EXISTS ix_offer_case_candidate ON offer_case(candidate_id);

ALTER TABLE offer ADD COLUMN IF NOT EXISTS offer_case_id BIGINT;
ALTER TABLE offer ADD COLUMN IF NOT EXISTS version_no INTEGER NOT NULL DEFAULT 1;
ALTER TABLE offer ADD COLUMN IF NOT EXISTS replaces_offer_version_id BIGINT;
ALTER TABLE offer ADD COLUMN IF NOT EXISTS needs_revision_reason VARCHAR(500);
ALTER TABLE offer ADD COLUMN IF NOT EXISTS submitted_at TIMESTAMP WITHOUT TIME ZONE;
ALTER TABLE offer ADD COLUMN IF NOT EXISTS approved_at TIMESTAMP WITHOUT TIME ZONE;
ALTER TABLE offer ADD COLUMN IF NOT EXISTS sealed_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE offer ADD COLUMN IF NOT EXISTS expired_at TIMESTAMP WITHOUT TIME ZONE;
ALTER TABLE offer ADD COLUMN IF NOT EXISTS withdrawn_at TIMESTAMP WITHOUT TIME ZONE;
ALTER TABLE offer ADD COLUMN IF NOT EXISTS withdraw_reason VARCHAR(500);
ALTER TABLE offer ADD COLUMN IF NOT EXISTS deadline_extension_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE offer ADD COLUMN IF NOT EXISTS legacy_review_required BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE offer DROP CONSTRAINT IF EXISTS fk_offer_case;
ALTER TABLE offer ADD CONSTRAINT fk_offer_case
    FOREIGN KEY (offer_case_id) REFERENCES offer_case(id);

ALTER TABLE offer DROP CONSTRAINT IF EXISTS fk_offer_replaces_version;
ALTER TABLE offer ADD CONSTRAINT fk_offer_replaces_version
    FOREIGN KEY (replaces_offer_version_id) REFERENCES offer(id);

ALTER TABLE offer DROP CONSTRAINT IF EXISTS ck_offer_status;
ALTER TABLE offer ADD CONSTRAINT ck_offer_status CHECK (status IN (
    'DRAFT', 'PENDING_APPROVAL', 'NEEDS_REVISION', 'APPROVED', 'SENT', 'ACCEPTED', 'DECLINED',
    'EXPIRED', 'WITHDRAWN', 'REJECTED'));

ALTER TABLE offer DROP CONSTRAINT IF EXISTS ck_offer_version_no;
ALTER TABLE offer ADD CONSTRAINT ck_offer_version_no CHECK (version_no >= 1);

-- ck_offer_sealed_matches_issued and ck_offer_withdraw_reason are added after the backfill in
-- section 6: PostgreSQL validates a new CHECK against existing rows, and until the backfill has
-- stamped sealed_at on the already-issued offers those rows would not satisfy it.

CREATE UNIQUE INDEX IF NOT EXISTS ux_offer_case_version
    ON offer(offer_case_id, version_no) WHERE offer_case_id IS NOT NULL;

-- At most one live version per case: a replacement may only be created after the previous one is
-- withdrawn, expired or answered. Quarantined legacy rows are excluded for the reason given on
-- ux_offer_case_open_application above.
CREATE UNIQUE INDEX IF NOT EXISTS ux_offer_case_single_active_version
    ON offer(offer_case_id)
    WHERE offer_case_id IS NOT NULL
      AND deleted_at IS NULL
      AND legacy_review_required = FALSE
      AND status IN ('DRAFT', 'PENDING_APPROVAL', 'NEEDS_REVISION', 'APPROVED', 'SENT');

CREATE INDEX IF NOT EXISTS ix_offer_offer_case ON offer(offer_case_id);

