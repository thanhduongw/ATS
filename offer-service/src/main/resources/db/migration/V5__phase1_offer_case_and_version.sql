CREATE TABLE IF NOT EXISTS offer_migration_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_offer_id BIGINT NOT NULL,
    offer_case_id BIGINT,
    legacy_status VARCHAR(32),
    disposition VARCHAR(40) NOT NULL,
    note VARCHAR(500),
    resolved_at TIMESTAMP WITH TIME ZONE,
    resolved_by_user_id BIGINT,
    resolution VARCHAR(32),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT ck_offer_migration_disposition CHECK (disposition IN (
        'MIGRATED', 'AWAITING_BUSINESS_DECISION'))
);

CREATE INDEX IF NOT EXISTS ix_offer_migration_report_disposition
    ON offer_migration_report(disposition);

CREATE TABLE IF NOT EXISTS offer_migration_summary (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    migration_version VARCHAR(20) NOT NULL,
    metric VARCHAR(80) NOT NULL,
    value BIGINT NOT NULL,
    ran_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------------------------
-- 5. Backfill
--
-- Every existing offer becomes version 1 of its own case. No status is reinterpreted:
--   * A legacy APPROVED row stays APPROVED. Before Phase 0 that value also made the offer visible
--     to the candidate, so it *might* have been seen; there is no column that records whether it
--     was. Rewriting it to SENT would claim a publication that may never have happened, and would
--     seal terms HR may still need to correct. It is flagged for a business decision instead.
--   * A legacy REJECTED row stays REJECTED. It recorded an approver refusal, which is now
--     NEEDS_REVISION, but consumers and reports may still key off the old value, so the rename is
--     a reviewed decision rather than a side effect of this migration. The REVISE edge accepts
--     the legacy value so those offers are not stuck in the meantime.
--   * SENT and later rows are sealed, because their terms genuinely are fixed.
-- ---------------------------------------------------------------------------------------------

DO $migration$
DECLARE
    legacy RECORD;
    new_case_id BIGINT;
    case_status TEXT;
    duplicate_open BOOLEAN;
    quarantined INTEGER := 0;
BEGIN
    FOR legacy IN
        -- Newest first, so when an application carries several live offers the most recent one
        -- keeps the clean case and the older ones are the quarantined duplicates.
        SELECT o.* FROM offer o
         WHERE o.offer_case_id IS NULL
         ORDER BY o.created_at DESC NULLS LAST, o.id DESC
    LOOP
        case_status := CASE legacy.status::TEXT
                           WHEN 'ACCEPTED' THEN 'CLOSED_ACCEPTED'
                           WHEN 'DECLINED' THEN 'CLOSED_DECLINED'
                           WHEN 'EXPIRED' THEN 'CLOSED_EXPIRED'
                           WHEN 'WITHDRAWN' THEN 'CLOSED_WITHDRAWN'
                           WHEN 'REJECTED' THEN 'CLOSED_CANCELLED'
                           ELSE 'OPEN'
                       END;
        -- A soft-deleted draft is not an open negotiation and must not block a new one.
        IF legacy.deleted_at IS NOT NULL AND case_status = 'OPEN' THEN
            case_status := 'CLOSED_CANCELLED';
        END IF;

        duplicate_open := case_status = 'OPEN' AND EXISTS (
            SELECT 1 FROM offer_case c
             WHERE c.application_id = legacy.application_id
               AND c.status = 'OPEN'
               AND c.legacy_review_required = FALSE);
        IF duplicate_open THEN
            quarantined := quarantined + 1;
        END IF;

        INSERT INTO offer_case(
            application_id, department_id, assigned_recruiter_id, candidate_id,
            candidate_name_snapshot, status, current_offer_id, version_counter, closed_at,
            legacy_review_required, version, created_at, updated_at)
        VALUES (
            legacy.application_id, legacy.department_id, legacy.assigned_recruiter_id,
            legacy.candidate_id, legacy.candidate_name_snapshot, case_status, legacy.id, 1,
            CASE WHEN case_status = 'OPEN' THEN NULL ELSE now() END,
            duplicate_open, 0, COALESCE(legacy.created_at, now()), now())
        RETURNING id INTO new_case_id;

        UPDATE offer
           SET offer_case_id = new_case_id,
               version_no = 1,
               legacy_review_required = duplicate_open,
               approved_at = CASE
                   WHEN status::TEXT IN ('APPROVED', 'SENT', 'ACCEPTED', 'DECLINED', 'EXPIRED')
                   THEN COALESCE(approved_at, issued_at, updated_at) ELSE approved_at END,
               submitted_at = CASE
                   WHEN status::TEXT <> 'DRAFT'
                   THEN COALESCE(submitted_at, created_at) ELSE submitted_at END,
               -- Only rows that really were published are frozen.
               sealed_at = CASE
                   WHEN status::TEXT IN ('SENT', 'ACCEPTED', 'DECLINED', 'EXPIRED')
                   THEN COALESCE(sealed_at, issued_at, updated_at, now()) ELSE sealed_at END,
               issued_at = CASE
                   WHEN status::TEXT IN ('SENT', 'ACCEPTED', 'DECLINED', 'EXPIRED')
                   THEN COALESCE(issued_at, updated_at, now()) ELSE issued_at END
         WHERE id = legacy.id;

        INSERT INTO offer_transition_log(
            offer_id, offer_case_id, version_no, aggregate_version, from_status, to_status,
            action, actor_user_id, actor_role, reason, admin_override, created_at)
        VALUES (legacy.id, new_case_id, 1, legacy.version, legacy.status::TEXT,
                legacy.status::TEXT, 'MIGRATE', NULL, 'SYSTEM',
                'Phase 1 backfill: existing offer became version 1 of its case', FALSE, now());

        INSERT INTO offer_migration_report(
            source_offer_id, offer_case_id, legacy_status, disposition, note)
        VALUES (
            legacy.id, new_case_id, legacy.status::TEXT,
            CASE WHEN duplicate_open OR legacy.status::TEXT IN ('APPROVED', 'REJECTED')
                 THEN 'AWAITING_BUSINESS_DECISION' ELSE 'MIGRATED' END,
            left(concat_ws(' ',
                CASE WHEN duplicate_open THEN
                    'The application already had another live offer. This one is quarantined out '
                    || 'of the one-open-case-per-application rule until HR decides which offer '
                    || 'stands; the other is withdrawn or the duplicate is deleted.' END,
                CASE legacy.status::TEXT
                    WHEN 'APPROVED' THEN
                        'Legacy APPROVED also meant candidate-visible. Confirm with HR whether '
                        || 'this offer was actually communicated: if it was, withdraw and reissue '
                        || 'it so a sealed version exists; if it was not, HR issues it normally.'
                    WHEN 'REJECTED' THEN
                        'Legacy REJECTED recorded an approver refusal, equivalent to '
                        || 'NEEDS_REVISION. Confirm no consumer or report depends on the old '
                        || 'value before renaming it.'
                    ELSE NULL
                END), 500));
    END LOOP;

    INSERT INTO offer_migration_summary(migration_version, metric, value)
    VALUES ('V5', 'offer_rows', (SELECT count(*) FROM offer)),
           ('V5', 'offer_cases_created', (SELECT count(*) FROM offer_case)),
           ('V5', 'sealed_versions', (SELECT count(*) FROM offer WHERE sealed_at IS NOT NULL)),
           ('V5', 'quarantined_duplicate_open_cases', quarantined),
           ('V5', 'awaiting_business_decision',
            (SELECT count(*) FROM offer_migration_report
              WHERE disposition = 'AWAITING_BUSINESS_DECISION'));
END
$migration$;

-- ---------------------------------------------------------------------------------------------
-- 6. Invariants that only hold once the backfill has run
--
-- Adding these earlier would fail: PostgreSQL validates a new CHECK against every existing row,
-- and the already-issued offers only get their sealed_at above.
-- ---------------------------------------------------------------------------------------------

-- A version cannot be reported as issued to the candidate without being sealed, and cannot be
-- sealed without having been issued. This is the pair the immutability trigger relies on.
ALTER TABLE offer DROP CONSTRAINT IF EXISTS ck_offer_sealed_matches_issued;
ALTER TABLE offer ADD CONSTRAINT ck_offer_sealed_matches_issued CHECK (
    status NOT IN ('SENT', 'ACCEPTED', 'DECLINED', 'EXPIRED')
    OR (sealed_at IS NOT NULL AND issued_at IS NOT NULL));

ALTER TABLE offer DROP CONSTRAINT IF EXISTS ck_offer_withdraw_reason;
ALTER TABLE offer ADD CONSTRAINT ck_offer_withdraw_reason CHECK (
    status <> 'WITHDRAWN' OR withdraw_reason IS NOT NULL);
