CREATE TABLE IF NOT EXISTS offer_transition_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id BIGINT NOT NULL,
    offer_case_id BIGINT,
    version_no INTEGER,
    aggregate_version BIGINT,
    from_status VARCHAR(32) NOT NULL,
    to_status VARCHAR(32) NOT NULL,
    action VARCHAR(32) NOT NULL,
    actor_user_id BIGINT,
    actor_role VARCHAR(32),
    reason VARCHAR(500),
    admin_override BOOLEAN NOT NULL DEFAULT FALSE,
    correlation_id VARCHAR(120),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_offer_transition_override_reason
        CHECK (admin_override = FALSE OR reason IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS ix_offer_transition_log_offer
    ON offer_transition_log(offer_id, created_at);
CREATE INDEX IF NOT EXISTS ix_offer_transition_log_case
    ON offer_transition_log(offer_case_id, created_at);

-- ---------------------------------------------------------------------------------------------
-- 3. Sealed-version immutability
--
-- Once a version has been issued, its terms are what the candidate was given. Only the outcome
-- columns may still move (the response, expiry, withdrawal and bookkeeping). Enforcing this in the
-- database rather than only in the service is the point: an admin console, a repair script or a
-- future code path cannot quietly rewrite a document somebody has already accepted.
-- ---------------------------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION offer_sealed_version_is_immutable() RETURNS trigger AS $trigger$
BEGIN
    IF OLD.sealed_at IS NULL THEN
        RETURN NEW;
    END IF;
    IF NEW.salary_offered IS DISTINCT FROM OLD.salary_offered
       OR NEW.contract_type_id IS DISTINCT FROM OLD.contract_type_id
       OR NEW.start_date IS DISTINCT FROM OLD.start_date
       OR NEW.probation_months IS DISTINCT FROM OLD.probation_months
       OR NEW.benefits IS DISTINCT FROM OLD.benefits
       OR NEW.allowance IS DISTINCT FROM OLD.allowance
       OR NEW.candidate_visible_note IS DISTINCT FROM OLD.candidate_visible_note
       OR NEW.application_id IS DISTINCT FROM OLD.application_id
       OR NEW.candidate_id IS DISTINCT FROM OLD.candidate_id
       OR NEW.offer_case_id IS DISTINCT FROM OLD.offer_case_id
       OR NEW.version_no IS DISTINCT FROM OLD.version_no
       OR NEW.issued_at IS DISTINCT FROM OLD.issued_at
       OR NEW.sealed_at IS DISTINCT FROM OLD.sealed_at
    THEN
        RAISE EXCEPTION
            'Offer version % is sealed; withdraw it and issue a new version instead', OLD.id
            USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END;
$trigger$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_offer_sealed_version_immutable ON offer;
CREATE TRIGGER trg_offer_sealed_version_immutable
    BEFORE UPDATE ON offer
    FOR EACH ROW EXECUTE FUNCTION offer_sealed_version_is_immutable();

